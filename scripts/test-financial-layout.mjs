const cache = new Map();
function load(relative) {
  const path = resolve(root, relative);
  if (cache.has(path)) return cache.get(path).exports;
  const source = readFileSync(path, 'utf8');
  const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, esModuleInterop: true } }).outputText;
  const module = new Module(path);
  cache.set(path, module);
  module.require = (id) => {
    if (!id.startsWith('.') && !id.startsWith('@/')) return require(id);
    const absolute = id.startsWith('@/') ? resolve(root, 'src', id.slice(2)) : resolve(dirname(path), id);
    if (absolute === resolve(root, 'src/features/finance/OperationForm')) return { fieldClass: 'test-field' };
    const candidate = [absolute, absolute + '.ts', absolute + '.tsx'].find(existsSync);
    if (!candidate) throw new Error(`Missing module: ${id}`);
    return load(candidate);
  };
  module._compile(compiled, path);
  return module.exports;
}
